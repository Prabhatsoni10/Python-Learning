#Logical Operators are used to combine two or more conditions. They return either True or False depending on the result of the combined conditions. They are mainly used in conditional statements such as if, elif, else, and while.

#Logical Operators
#Operator	Meaning
#and	Returns True if both conditions are True.
#or	Returns True if at least one condition is True.
#not	Reverses the result (True becomes False and False becomes True).