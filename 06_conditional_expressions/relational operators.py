#Relational (Comparison) Operators are used to compare two values or variables. They evaluate a condition and always return either True or False. They are mainly used in conditional statements such as if, elif, else, and while.

#Relational Operators
#Operator	Meaning
#==	Equal to
#!=	Not Equal to
#>	Greater Than
#<	Less Than
#>=	Greater Than or Equal to
#<=	Less Than or Equal to